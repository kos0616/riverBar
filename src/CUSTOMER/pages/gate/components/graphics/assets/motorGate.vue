<script lang="ts" setup>
/**
 * 馬達顯示
 * 在水門使用
 * 以燈號和旋轉的手把表示馬達運作狀態
 * 參考資料:
 * g01State.isMotorError ? 'dynamic-color-error' : '',
 * g01State.isOpening || g01State.isClosing ? 'dynamic-color-working-shine' : 'fill-online',
 * g01State.isMotorOn ? 'fill-online' : 'fill-online'

 */
import { computed } from 'vue';

interface Props {
  status?: 'error' | 'working' | 'online' | 'offline';
}

const props = defineProps<Props>();

/** 馬達燈號 */
const lightClass = computed(() => {
  switch (props.status) {
    case 'error':
      return 'dynamic-color-error';
    case 'working':
      return 'dynamic-color-working-shine';
    case 'online':
      return 'fill-online';
    default:
      return 'fill-online';
  }
});

/** 方向盤 */
const handleBarClass = computed(() => {
  switch (props.status) {
    case 'working':
      return 'fa-spin';
    case 'error':
      return 'fa-spin is-error';
    default:
      return '';
  }
  // props.status === 'working' ? 'fa-spin' : ''
});
</script>

